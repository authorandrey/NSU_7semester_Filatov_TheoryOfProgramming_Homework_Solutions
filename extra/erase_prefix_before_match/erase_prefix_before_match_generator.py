#!/usr/bin/env python3
"""Generate a one-tape Turing machine that erases the prefix before the
leftmost occurrence of a fixed pattern over the alphabet {a,b}.

Usage:
    python erase_prefix_before_match_generator.py PATTERN
    python erase_prefix_before_match_generator.py PATTERN output.tur

If the pattern is found, it and the suffix remain. If it is absent, the
entire input word is erased. The tape alphabet is fixed to {#, a, b}.
"""

from __future__ import annotations

import sys
from pathlib import Path

ALPHABET = "ab"
DEFAULT_OUTPUT = "erase_prefix_before_match.tur"


def validate_pattern(pattern: str) -> None:
    if not pattern:
        raise ValueError("PATTERN must be a non-empty word over {a,b}")
    invalid = sorted(set(pattern) - set(ALPHABET))
    if invalid:
        raise ValueError(
            "PATTERN may contain only 'a' and 'b'; invalid symbols: "
            + ", ".join(repr(c) for c in invalid)
        )


def delta(pattern: str, matched: int, symbol: str) -> int:
    """KMP fallback: longest proper prefix of pattern that is a suffix of
    pattern[:matched] + symbol.
    """
    candidate = pattern[:matched] + symbol
    limit = min(len(pattern) - 1, len(candidate))
    for length in range(limit, -1, -1):
        if candidate.endswith(pattern[:length]):
            return length
    return 0


def generate_mt(pattern: str) -> str:
    """Return a complete emulator program for the given pattern."""
    validate_pattern(pattern)
    length = len(pattern)
    lines: list[str] = [
        "// Generated by erase_prefix_before_match_generator.py",
        f"// Pattern P = {pattern}",
        "// If found: erase the prefix before the leftmost match.",
        "// If absent: erase the entire input word.",
        "alphabet = [#, a, b]",
        "tapes = [ right ]",
        "",
        "START:",
        "    # -> #R Search_0",
        "",
    ]

    # Search_i stores the length of the longest suffix of the consumed input
    # that is also a proper prefix of the pattern.
    for matched in range(length):
        lines.append(f"Search_{matched}:")
        for symbol in ALPHABET:
            if matched == length - 1 and symbol == pattern[-1]:
                # This is the earliest point at which any match is complete.
                if length == 1:
                    lines.append(f"    {symbol} -> {symbol}H STOP")
                else:
                    lines.append(f"    {symbol} -> {symbol}L Restore_{length - 1}")
            else:
                next_matched = delta(pattern, matched, symbol)
                lines.append(f"    {symbol} -> #R Search_{next_matched}")
        # Every consumed input symbol was erased; this # is the right boundary.
        lines.append("    # -> #H STOP")
        lines.append("")

    # Previously scanned symbols of the match were erased, so restore them
    # right-to-left while moving left from its final character.
    if length > 1:
        for restore_index in range(length - 1, 0, -1):
            restored_symbol = pattern[restore_index - 1]
            if restore_index == 1:
                action = f"{restored_symbol}H STOP"
            else:
                action = f"{restored_symbol}L Restore_{restore_index - 1}"
            lines.append(f"Restore_{restore_index}:")
            for read_symbol in "#ab":
                lines.append(f"    {read_symbol} -> {action}")
            lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    args = sys.argv[1:]
    if len(args) not in (1, 2):
        print(
            f"Usage: {Path(sys.argv[0]).name} PATTERN [output.tur]",
            file=sys.stderr,
        )
        return 2

    pattern = args[0]
    output = Path(args[1] if len(args) == 2 else DEFAULT_OUTPUT)
    try:
        program = generate_mt(pattern)
        output.write_text(program, encoding="utf-8")
    except (ValueError, OSError) as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1

    print(f"Generated {output} for pattern {pattern!r}.")
    print(f"Transition rules: {sum('->' in line for line in program.splitlines())}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
